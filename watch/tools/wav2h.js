// Usage: node wav2h.js in.wav out.h name
// Rewrites any PCM WAV with a clean 44-byte header (what LilyGoLib playWAV expects) and emits a C array.
const fs=require('fs');const [,,inp,out,name]=process.argv;const b=fs.readFileSync(inp);
if(b.toString('ascii',0,4)!=='RIFF'||b.toString('ascii',8,12)!=='WAVE') throw 'not wav';
let p=12,fmt=null,data=null;
while(p+8<=b.length){const id=b.toString('ascii',p,p+4),sz=b.readUInt32LE(p+4);if(id==='fmt ')fmt=b.subarray(p+8,p+8+sz);if(id==='data')data=b.subarray(p+8,Math.min(b.length,p+8+sz));p+=8+sz+(sz&1);}
if(!fmt||!data) throw 'missing chunk';
if(fmt.readUInt16LE(0)!==1) throw 'not PCM';
const ch=fmt.readUInt16LE(2),rate=fmt.readUInt32LE(4),bits=fmt.readUInt16LE(14);
const h=Buffer.alloc(44);h.write('RIFF',0);h.writeUInt32LE(36+data.length,4);h.write('WAVE',8);h.write('fmt ',12);h.writeUInt32LE(16,16);
h.writeUInt16LE(1,20);h.writeUInt16LE(ch,22);h.writeUInt32LE(rate,24);h.writeUInt32LE(rate*ch*bits/8,28);h.writeUInt16LE(ch*bits/8,32);h.writeUInt16LE(bits,34);h.write('data',36);h.writeUInt32LE(data.length,40);
const all=Buffer.concat([h,data]);
let s=`// ${name}: PCM WAV, ${rate} Hz, ${bits}-bit, ${ch} ch, ${all.length} bytes. Generated by wav2h.js.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\nconst uint8_t ${name}_wav[] = {\n`;
for(let i=0;i<all.length;i+=16){s+='  '+[...all.subarray(i,i+16)].map(v=>'0x'+v.toString(16).padStart(2,'0')).join(', ')+',\n';}
s+=`};\nconst size_t ${name}_wav_len = sizeof(${name}_wav);\n`;fs.writeFileSync(out,s);console.log(rate,bits,ch,all.length,'bytes');
